import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const themes = ['glass', 'material', 'minimal'];
const modes = ['light', 'dark'];
const required = [
  '--app-bg', '--surface', '--stroke', '--text', '--gutter', '--accent', '--accent-soft',
  '--selection-bg', '--hover', '--scrollbar-thumb', '--scrollbar-thumb-hover', '--err', '--warn',
  '--md-heading', '--md-strong', '--md-emphasis', '--md-quote', '--md-link', '--md-comment',
  '--md-marker', '--code-fg', '--hl-keyword', '--hl-string', '--hl-comment', '--hl-number',
  '--hl-function', '--hl-type', '--hl-attr', '--hl-punct',
];

const markdownRules = [
  ['keyword', '--md-heading'], ['meta.separator', '--md-marker'], ['keyword.table.*', '--md-marker'],
  ['strong', '--md-strong'], ['emphasis', '--md-emphasis'], ['comment', '--md-quote'],
  ['comment.*', '--md-quote'], ['string.link', '--md-link'], ['string.target', '--md-link'],
  ['string', '--md-comment'], ['variable.source', '--code-fg'],
];
const goRules = [
  ['keyword', '--hl-keyword'], ['keyword.*', '--hl-keyword'], ['string', '--hl-string'],
  ['comment', '--hl-comment'], ['comment.*', '--hl-comment'], ['number', '--hl-number'],
  ['number.*', '--hl-number'], ['delimiter', '--hl-punct'], ['delimiter.*', '--hl-punct'],
  ['annotation', '--hl-attr'], ['identifier', '--hl-function'], ['keyword.type', '--hl-type'],
  ['keyword.const', '--hl-type'],
];

function blocks(css) {
  return [...css.matchAll(/([^{}]+)\{([^{}]*)\}/g)].map(([, selector, declarations]) => ({
    selector: selector.trim(),
    declarations: Object.fromEntries([...declarations.matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g)].map(([, name, value]) => [name, value.trim()])),
  }));
}

function applies(selector, theme, mode) {
  if (!selector.includes(':root')) return false;
  const selectorTheme = selector.match(/data-theme=['"](glass|material|minimal)['"]/);
  const selectorMode = selector.match(/data-mode=['"](light|dark)['"]/);
  return (!selectorTheme || selectorTheme[1] === theme) && (!selectorMode || selectorMode[1] === mode);
}

function resolvedTokens(css, theme, mode) {
  const values = {};
  for (const block of blocks(css)) {
    if (applies(block.selector, theme, mode)) Object.assign(values, block.declarations);
  }
  for (const token of required) {
    if (!values[token]) throw new Error(`Missing required token ${token} for ${theme}/${mode}`);
  }
  return values;
}

function rulesFor(values) {
  return [...markdownRules, ...goRules].map(([token, cssToken]) => ({ token, foreground: values[cssToken] }));
}

export function generateEditorThemes(css) {
  const definitions = {};
  for (const theme of themes) for (const mode of modes) {
    const values = resolvedTokens(css, theme, mode);
    definitions[`gme-${theme}-${mode}`] = {
      base: mode === 'dark' ? 'vs-dark' : 'vs',
      inherit: true,
      colors: {
        'editor.background': values['--app-bg'], 'editor.foreground': values['--text'],
        'editorLineNumber.foreground': values['--gutter'], 'editorLineNumber.activeForeground': values['--text'],
        'editorCursor.foreground': values['--accent'], 'editor.selectionBackground': values['--selection-bg'],
        'editor.selectionHighlightBackground': values['--selection-bg'], 'editor.lineHighlightBackground': values['--hover'],
        'editorGutter.background': values['--app-bg'], 'editorWidget.background': values['--surface'],
        'editorWidget.border': values['--stroke'], 'editorSuggestWidget.background': values['--surface'],
        'editorSuggestWidget.foreground': values['--text'], 'editorSuggestWidget.selectedBackground': values['--accent-soft'],
        'minimap.background': values['--app-bg'], 'scrollbarSlider.background': values['--scrollbar-thumb'],
        'scrollbarSlider.hoverBackground': values['--scrollbar-thumb-hover'], 'editorError.foreground': values['--err'],
        'editorWarning.foreground': values['--warn'],
      },
      rules: rulesFor(values),
    };
  }
  const highlightCss = Object.entries(definitions).map(([name, definition]) => {
    const keyword = definition.rules.find((rule) => rule.token === 'keyword').foreground;
    return `[data-gme-highlight='${name}'] .hljs-keyword { color: ${keyword}; }`;
  }).join('\n');
  return { themes: definitions, highlightCss };
}

export async function generateFiles({ input, themesOutput, highlightOutput }) {
  const generated = generateEditorThemes(await readFile(input, 'utf8'));
  const editorSource = `// Generated by scripts/generate-editor-themes.mjs. Do not edit.\nexport const generatedEditorThemes = ${JSON.stringify(generated.themes, null, 2)} as const;\nexport type GeneratedEditorThemeName = keyof typeof generatedEditorThemes;\n`;
  await Promise.all([writeFile(themesOutput, editorSource), writeFile(highlightOutput, `${generated.highlightCss}\n`)]);
  return generated;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const root = new URL('..', import.meta.url);
  await generateFiles({
    input: new URL('../src/ui/styles/tokens.css', import.meta.url),
    themesOutput: new URL('../src/logic/theme/generatedEditorThemes.ts', import.meta.url),
    highlightOutput: new URL('../src/logic/theme/generatedHighlight.css', import.meta.url),
  });
}
